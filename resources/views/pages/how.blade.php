<article class="prose">
    <h1>Как это работает</h1>
    <p class="upd">Коротко о том, что происходит с вашими донатами.</p>

    <h2>Схема</h2>
    <p>Зритель отправляет донат через DonationAlerts. Наш сервер, подключённый к DonationAlerts от вашего имени, получает уведомление и сразу передаёт его в канал вашего виджета. Виджет StreamElements подписан на этот канал по личному токену и показывает донат на стриме.</p>

    <h2>Подключение</h2>
    <ul>
        <li>Нажмите «Войти» и подтвердите доступ на сайте DonationAlerts.</li>
        <li>В личном кабинете скопируйте токен виджета.</li>
        <li>Вставьте токен в настройки своего виджета в StreamElements.</li>
    </ul>

    <h2>Какие права мы запрашиваем</h2>
    <ul>
        <li><b>Чтение профиля</b> — чтобы узнать ваш ID, имя и аватар.</li>
        <li><b>Подписка на донаты</b> — чтобы получать уведомления о новых донатах.</li>
    </ul>
    <p>Эти права не позволяют выводить деньги, видеть платёжные реквизиты или менять настройки аккаунта.</p>

    <h2>Что хранится</h2>
    <p>Профиль, токены доступа (в зашифрованном виде), токен виджета и история полученных донатов. Подробности в <a href="{{ route('privacy') }}">Политике конфиденциальности</a>.</p>

    <h2>Безопасность токена</h2>
    <p>Токен виджета — это «пароль» к вашему каналу донатов: любой, кто его знает, увидит ваши донаты. Если токен попал не туда, создайте новый в кабинете, и старый сразу перестанет работать.</p>

    <h2>Отключение</h2>
    <p>Вы можете удалить аккаунт и все данные в личном кабинете в любой момент. Дополнительно отзовите доступ приложения в настройках DonationAlerts.</p>

    <h2>Ограничения</h2>
    <p>Сервис работает по принципу «как есть». При сбоях связи уведомления могут прийти с задержкой или не прийти. Историю платежей и бухгалтерский учёт нужно вести в самом DonationAlerts. Подробнее в <a href="{{ route('terms') }}">Условиях использования</a>.</p>
